import assert from "node:assert/strict";
import { createServer } from "node:http";
import { mkdir, mkdtemp, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { ImageGenClient } from "../node/client.js";
import { RequestError } from "../node/errors.js";

// A one-pixel PNG fixture. This demo verifies the integration, not model quality.
const image = Buffer.from(
  "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAIAAACQd1PeAAAADElEQVR4nGM4MisHAAPwAcuxRVC2AAAAAElFTkSuQmCC",
  "base64",
);
const parent = resolve(process.argv[2] || "output/imagegen-demo");
await mkdir(parent, { recursive: true });
const directory = await mkdtemp(resolve(parent, "run-"));
const source = resolve(directory, "input-fixture.png");
await writeFile(source, image);

const requests = [];
const server = createServer(async (request, response) => {
  const chunks = [];
  for await (const chunk of request) chunks.push(chunk);
  const body = Buffer.concat(chunks);
  if (request.method !== "POST") {
    response.writeHead(405).end();
    return;
  }
  if (!["/v1/images/generations", "/v1/images/edits"].includes(request.url)) {
    response.writeHead(404).end();
    return;
  }
  if (request.headers.authorization !== "Bearer local-demo-key") {
    response.writeHead(401).end();
    return;
  }
  const generation = request.url.endsWith("/generations");
  const payload = generation ? JSON.parse(body.toString("utf8")) : undefined;
  if (generation) {
    assert.equal(payload.n, 1);
  } else {
    assert.match(request.headers["content-type"], /^multipart\/form-data/u);
    assert.ok(body.includes(image));
  }
  requests.push({ operation: generation ? "generate" : "edit", path: request.url });
  response.writeHead(200, { "content-type": "application/json" });
  response.end(JSON.stringify({ data: [{ b64_json: image.toString("base64") }] }));
});

await new Promise((done) => server.listen(0, "127.0.0.1", done));
try {
  const client = new ImageGenClient({
    provider: "openai-compatible",
    baseUrl: `http://127.0.0.1:${server.address().port}/v1`,
    apiKeyEnv: "IMAGEGEN_API_KEY",
    apiKey: "local-demo-key",
    model: "local-png-fixture",
    timeoutSeconds: 10,
    maxRetries: 0,
    headers: {},
    size: "auto",
    quality: "auto",
    outputFormat: "png",
    outputDir: directory,
  });
  const generated = await client.generate({
    prompt: "A ceramic mug on a neutral background",
    out: resolve(directory, "generated-fixture.png"),
  });
  const edited = await client.edit({
    prompt: "Change only the background; preserve the mug",
    images: [generated.outputs[0]],
    out: resolve(directory, "edited-fixture.png"),
  });
  for (const path of [...generated.outputs, ...edited.outputs]) {
    assert.deepEqual(await readFile(path), image);
  }
  await assert.rejects(
    client.generate({ prompt: "Invalid image count", n: 0 }),
    RequestError,
  );
  assert.equal(requests.length, 2, "The rejected request must not reach the provider");

  const evidence = {
    status: "ok",
    verification: "local API and output-file integration only",
    images: "one-pixel fixtures; not generated by an AI model",
    operations: requests,
    input: source,
    outputs: [...generated.outputs, ...edited.outputs],
    rejected_zero_before_network: true,
  };
  const manifest = resolve(directory, "verification.json");
  await writeFile(manifest, `${JSON.stringify(evidence, null, 2)}\n`, "utf8");
  console.log(JSON.stringify({ ...evidence, manifest }, null, 2));
} finally {
  await new Promise((done) => server.close(done));
}
